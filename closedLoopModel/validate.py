r"""Validation of the closed-loop model on the time sequences recorded on LUCY.

1. Sequences: moves, current scale (saturation, rigid-body balance), holding torques at rest.
2. Estimate of the effective drive gains and of the bearing friction level of each axis on the windows of the
   identification sequence (:mod:`lucy_cl.identification`), starting from the .akd files.
3. Validation on every move of the other sequences, with the nominal model (.akd parameters) and with the
   estimated parameters: fit NRMSE of the position error and of the current of the moving axis, disturbance on
   the held axis.

Results in ``<results_dir>/``: ``figures/``, ``summary.md``, ``summary.json``.

Usage (from this folder)::

    ../.venv/bin/python -I validate.py --config config_validation.yaml
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import sys
import time
from pathlib import Path

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import main as mn  # noqa: E402
from lucy_cl import AXES  # noqa: E402
from lucy_cl import identification as idn  # noqa: E402
from lucy_cl import output as out  # noqa: E402
from lucy_cl.validation import read_sequence, rigid_body_regression  # noqa: E402

MDEG = out.MDEG


def fit(meas: np.ndarray, model: np.ndarray) -> float:
    ok = np.isfinite(model)
    if ok.sum() < 10:
        return float("nan")
    from gimbal_mdof.sperimentale import fit_nrmse

    return fit_nrmse(meas[ok], model[ok])


def window_figure(results: list[tuple[idn.Window, dict, dict]], title: str):
    """Rows: windows; columns: position error and current of the moving axis, error of the held axis."""
    import matplotlib.pyplot as plt

    n = len(results)
    fig, ax = plt.subplots(n, 3, figsize=(13.5, 2.3 * n + 0.6), squeeze=False)
    for k, (w, nom, ide) in enumerate(results):
        held = [a for a in AXES if a != w.axis][0]
        t = nom["t"]
        for j, (axis, key, scale, unit) in enumerate(((w.axis, "error", MDEG, "mdeg"),
                                                      (w.axis, "current", 1.0, "A rms"),
                                                      (held, "error", MDEG, "mdeg"))):
            a = ax[k, j]
            a.plot(t, scale * nom[axis][f"{key}_meas"], "k", lw=1.4, label="measured")
            a.plot(t, scale * nom[axis][key], "C3--", lw=1.0, label="model, .akd parameters")
            a.plot(t, scale * ide[axis][key], "C0", lw=1.0, label="model, estimated parameters")
            lab = {"error": "command - encoder", "current": "current"}[key]
            a.set_title(f"{w.sequence} {w.move:.2f} s, {axis} {lab}" + (" (held)" if axis == held else ""),
                        fontsize=7.5)
            a.set_ylabel(unit)
            if k == n - 1:
                a.set_xlabel("time from window start [s]")
    ax[0, 0].legend(fontsize=6.5)
    fig.suptitle(title, fontsize=9)
    fig.tight_layout()
    return fig


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default="config_validation.yaml")
    ap.add_argument("--skip-identification", action="store_true",
                    help="reuse the parameters of a previous summary.json")
    ap.add_argument("--start-from-previous", action="store_true",
                    help="start the estimate from the parameters of a previous summary.json")
    args = ap.parse_args()
    cfg_path = Path(args.config).resolve()
    base = cfg_path.parent
    vc = yaml.safe_load(cfg_path.read_text())
    cfg = yaml.safe_load((base / vc["base_config"]).read_text())
    res_dir = base / vc["results_dir"]
    fig_dir = res_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    seq_dir = (base / vc["sequences_dir"]).resolve()
    amps = float(vc.get("amps_per_A", 2.0))
    t_start = time.time()
    js: dict = {"config": cfg_path.name, "base_config": vc["base_config"]}
    md = [f"# Validation of the closed-loop model on the time sequences", "",
          f"Configuration `{cfg_path.name}` (model `{vc['base_config']}`: {cfg.get('label', '')}). "
          f"Generated by `validate.py`.", ""]

    cl, _, _ = mn.build(cfg, base)
    nominal = {ax: idn.current_values(cl, ax) for ax in AXES}

    # ---- 1. sequences ---------------------------------------------------------------------------------
    names = [vc["identification"]["sequence"]] + list(vc["validation"]["sequences"])
    seqs = {n: read_sequence(seq_dir / f"{n}.csv", amps) for n in names}
    rows = []
    for n, s in seqs.items():
        for ax in AXES:
            mv = s.moves(ax)
            amp = sorted({round(abs(np.rad2deg(s.cmd[ax][s.t <= b][-1] - s.cmd[ax][s.t <= a][-1])), 1) for a, b in mv})
            rows.append([n, ax, len(mv), ", ".join(f"{x:g}" for x in amp),
                         f"{np.abs(s.current[ax]).max() * amps:.1f}"])
    md += ["## 1. Sequences", "", "2 kHz, about 100 s each; positions in millidegrees (360000 per revolution, "
           "encoder step 0.343 mdeg); AXIS1 = azimuth, AXIS2 = elevation. Commands: trapezoidal speed profiles, "
           "15 deg/s and 200 deg/s^2.", "",
           out.markdown_table(["sequence", "axis", "moves", "amplitudes [deg]", "max |AMPS|"], rows), ""]
    J = {}
    M, _, _ = cl.plant.linear_matrices()
    for ax in AXES:  # rigid inertia of each axis: sum of its block of the mass matrix (rotors included)
        n_psi = cl.plant.sim.struttura.n_psi
        sl = slice(0, n_psi) if ax == "azimuth" else slice(n_psi, cl.plant.n)
        J[ax] = float(np.sum(M[sl, sl]))
    rows = []
    js["current_scale"] = {}
    for n, s in seqs.items():
        for ax in AXES:
            rr = rigid_body_regression(s, ax, J[ax])
            js["current_scale"][f"{n}/{ax}"] = rr
            rows.append([n, ax, f"{rr['slope']:.2f}", f"{rr['torque_per_unit']:.4f}",
                         f"{rr['torque_per_unit'] * amps:.3f}", f"{rr['coulomb_Nm']:.2f}", f"{rr['R2']:.3f}"])
    md += ["### Current scale", "",
           f"`AXIS*_AMPS` saturates at 35.9 = 2 x `IL.LIMITP` (18 A rms). Rigid-body balance of the moves "
           f"(encoder and current low-passed at 3 Hz, moving samples): AMPS = a d2q/dt2 + b sgn(dq/dt) + c; with "
           f"the rigid inertias of the model (azimuth {J['azimuth']:.3f}, elevation {J['elevation']:.3f} kg m^2) "
           f"J/a is the torque per AMPS unit. Scale used: 1 unit = {1 / amps:g} A rms. The torque channel of the "
           f"files is 0.1847 x AMPS (N m per unit 1.43 times J/a).", "",
           out.markdown_table(["sequence", "axis", "a [units/(rad/s^2)]", "J/a [N m/unit]",
                               f"J/a x {amps:g} [N m/A rms] (Kt = 0.258)", "Coulomb [N m]", "R^2"], rows), ""]

    # ---- 2. estimate -----------------------------------------------------------------------------------
    ic = vc["identification"]
    s_id = seqs[ic["sequence"]]
    wins = {ax: idn.windows_for_moves(s_id, ax, pre=ic["windows"][ax].get("pre_s", 0.3),
                                      post=ic["windows"][ax].get("post_s", 2.5), starts=ic["windows"][ax]["starts"])
            for ax in AXES}
    ctx = mp.get_context("fork")
    with ctx.Pool(int(vc.get("workers", 4)), initializer=idn._init_worker,
                  initargs=(cfg, str(base), str(seq_dir), amps)) as pool:
        est = {}
        if args.skip_identification:
            prev = json.loads((res_dir / "summary.json").read_text())
            est_vals = {ax: prev["estimate"][ax]["values"] for ax in AXES}
            js["estimate"] = prev["estimate"]
            md_prev = [f"{ax} {prev['estimate'][ax]['cost_start']:.3f} -> {prev['estimate'][ax]['cost']:.3f} "
                       f"({prev['estimate'][ax]['n_eval']} evaluations)" for ax in AXES
                       if "cost" in prev["estimate"][ax]]
        else:
            est_vals = {}
            prev = json.loads((res_dir / "summary.json").read_text()) if args.start_from_previous else None
            for ax in AXES:
                start = {k: nominal[ax][k] for k in ic["parameters"]}
                kpp0 = idn.cruise_gain(s_id, ax)
                if "Kpp" in start and np.isfinite(kpp0):
                    start["Kpp"] = kpp0
                if prev is not None:
                    start = {k: prev["estimate"][ax]["values"][k] for k in ic["parameters"]}
                print(f"  estimate {ax}: {len(wins[ax])} windows, start " + ", ".join(f"{k} {v:.4g}" for k, v in start.items()),
                      flush=True)
                e = idn.estimate(pool, ax, wins[ax], start,
                                 weights=(ic["weights"]["error"], ic["weights"]["current"]),
                                 max_nfev=int(ic.get("max_nfev", 40)), max_cpu=float(ic.get("max_cpu_per_window_s", 120)))
                est[ax] = e
                est_vals[ax] = e.values
            js["estimate"] = {ax: {"start": e.start, "values": e.values, "cost_start": e.cost_start, "cost": e.cost,
                                   "n_eval": e.n_eval, "windows": [w.label for w in e.windows]}
                              for ax, e in est.items()}
        js.setdefault("estimate", {})
        for ax in AXES:
            js["estimate"].setdefault(ax, {})["values"] = est_vals[ax]

        rows = []
        for ax in AXES:
            p_akd = cl.drives[ax].p
            for k in ic["parameters"]:
                nom = nominal[ax][k]
                e = est_vals[ax][k]
                extra = ""
                if k == "Kpp":
                    extra = (f"PL.KP = {p_akd.Kpp / (2 * np.pi):g}: model 2 pi PL.KP = {nom:.3g} 1/s; "
                             f"estimate = {e / (2 * np.pi):.3g} x 2 pi = {e / (p_akd.Kpp / (2 * np.pi)):.3g} x PL.KP")
                start_v = js["estimate"][ax].get("start", {}).get(k, float("nan"))
                rows.append([ax, k, f"{nom:.4g}", f"{start_v:.4g}", f"{e:.4g}", f"{e / nom:.3g}", extra])
        md += ["## 2. Effective drive gains and friction level", "",
               f"Least squares on the windows of `{ic['sequence']}` (moves at "
               + "; ".join(f"{ax}: " + ", ".join(f"{w.move:.2f}" for w in wins[ax]) + " s" for ax in AXES)
               + "), residuals of the position error and of the current normalised as the NRMSE fit. Start: "
               + ("the estimate of a previous run (itself started from the .akd values and from the position gain "
                  "given by the following error at constant speed)" if args.start_from_previous else
                  ".akd values, position gain from the following error at constant speed")
               + ". Kpp in 1/s, Kpv in A/(rad/s), Kiv in Hz, Tc (Coulomb level of the Dahl friction) in N m.", "",
               out.markdown_table(["axis", "parameter", "model (.akd / H6)", "start", "estimate",
                                   "estimate / model", "note"], rows), ""]
        if est:
            md += ["Cost (sum of (1 - fit)^2 over windows and channels): " + "; ".join(
                f"{ax} {e.cost_start:.3f} -> {e.cost:.3f} ({e.n_eval} evaluations)" for ax, e in est.items()), ""]
        elif args.skip_identification and md_prev:
            md += ["Cost (sum of (1 - fit)^2 over windows and channels; estimate of a previous run): "
                   + "; ".join(md_prev), ""]

        # ---- identification windows: figures ---------------------------------------------------------
        nom_vals = {ax: dict(nominal[ax]) for ax in AXES}
        for ax in AXES:
            jobs = [(w, nom_vals, float(ic.get("max_cpu_per_window_s", 120))) for w in wins[ax]]
            jobs_e = [(w, est_vals, float(ic.get("max_cpu_per_window_s", 120))) for w in wins[ax]]
            rn, re_ = pool.map(idn.simulate_job, jobs), pool.map(idn.simulate_job, jobs_e)
            fg = window_figure(list(zip(wins[ax], rn, re_)), f"identification windows, {ax} moves ({ic['sequence']})")
            out.save(fg, fig_dir, f"identification_{ax}")

        # ---- 3. validation -------------------------------------------------------------------------
        vv = vc["validation"]
        md += ["## 3. Validation", "",
               "Every move of the validation sequences, simulated from the measured state at rest before it with "
               "the measured commands of both axes. Fit NRMSE (%) of the moving axis; disturbance: largest "
               "|command - encoder| of the held axis during the window.", ""]
        js["validation"] = {}
        summary_rows, all_rows = [], []
        for n in vv["sequences"]:
            s = seqs[n]
            for ax in AXES:
                ws = idn.windows_for_moves(s, ax, pre=vv.get("pre_s", 0.3), post=vv.get("post_s", 2.5))
                if not ws:
                    continue
                mc = float(vv.get("max_cpu_per_window_s", 120))
                rn = pool.map(idn.simulate_job, [(w, nom_vals, mc) for w in ws])
                re_ = pool.map(idn.simulate_job, [(w, est_vals, mc) for w in ws])
                held = [a for a in AXES if a != ax][0]
                rec = []
                for w, a_, b_ in zip(ws, rn, re_):
                    r = {"window": w.label, "ok": [a_["ok"], b_["ok"]]}
                    for lab, o in (("akd", a_), ("estimate", b_)):
                        r[f"fit_error_{lab}"] = fit(o[ax]["error_meas"], o[ax]["error"])
                        r[f"fit_current_{lab}"] = fit(o[ax]["current_meas"], o[ax]["current"])
                        r[f"held_max_{lab}_mdeg"] = float(MDEG * np.nanmax(np.abs(o[held]["error"] - o[held]["error"][0])))
                    r["held_max_meas_mdeg"] = float(MDEG * np.max(np.abs(a_[held]["error_meas"] - a_[held]["error_meas"][0])))
                    cw = s.cmd[held][s.window(w.t0, w.t1)]
                    r["held_static"] = bool(np.ptp(cw) < 1e-7)
                    if not r["held_static"]:  # the other axis moves too: no disturbance measure
                        for k_ in ("held_max_meas_mdeg", "held_max_akd_mdeg", "held_max_estimate_mdeg"):
                            r[k_] = float("nan")
                    amp = np.rad2deg(s.cmd[ax][s.window(w.t0, w.t1)][-1] - s.cmd[ax][s.window(w.t0, w.t1)][0])
                    r["amplitude_deg"] = float(amp)
                    rec.append(r)
                    all_rows.append([n, ax, f"{w.move:.2f}", f"{amp:+.1f}",
                                     out.fmt(r["fit_error_akd"], 3), out.fmt(r["fit_error_estimate"], 3),
                                     out.fmt(r["fit_current_akd"], 3), out.fmt(r["fit_current_estimate"], 3),
                                     out.fmt(r["held_max_meas_mdeg"], 3), out.fmt(r["held_max_estimate_mdeg"], 3)])
                js["validation"][f"{n}/{ax}"] = rec

                def med(key: str) -> str:
                    v = np.array([r[key] for r in rec], dtype=float)
                    if np.all(np.isnan(v)):
                        return "-"
                    return f"{np.nanmedian(v):.1f} [{np.nanmin(v):.0f}, {np.nanmax(v):.0f}]"

                summary_rows.append([n, ax, len(rec), med("fit_error_akd"), med("fit_error_estimate"),
                                     med("fit_current_akd"), med("fit_current_estimate"),
                                     med("held_max_meas_mdeg"), med("held_max_estimate_mdeg")])
                order = np.argsort([-abs(r["amplitude_deg"]) for r in rec])
                pick = sorted(set(list(order[:3]) + list(order[-2:])))[:5]
                fg = window_figure([(ws[k], rn[k], re_[k]) for k in pick], f"validation: {n}, {ax} moves")
                out.save(fg, fig_dir, f"validation_{n}_{ax}")
                print(f"  validation {n} {ax}: {len(rec)} windows", flush=True)
        md += ["Median [min, max] over the moves:", "",
               out.markdown_table(["sequence", "axis", "moves", "fit error .akd", "fit error estimate",
                                   "fit current .akd", "fit current estimate", "held axis: measured [mdeg]",
                                   "held axis: model [mdeg]"], summary_rows), "",
               "Held axis: only the moves during which the other axis has a constant command.", "",
               "<details><summary>All moves</summary>", "",
               out.markdown_table(["sequence", "axis", "start [s]", "move [deg]", "fit error .akd",
                                   "fit error estimate", "fit current .akd", "fit current estimate",
                                   "held measured [mdeg]", "held model [mdeg]"], all_rows), "", "</details>", ""]

    md += ["## Notes", "",
           "- Model: closed loop of `main.py` with the base configuration; the estimate replaces Kpp, Kpv, Kiv of the "
           "drives and the Coulomb level of the Dahl friction (sigma0 of H6 kept); filters, observer, current loop "
           "and limits of the .akd files.",
           "- Windows start at rest from the measurement: encoder positions, holding currents carried by the "
           "friction state, integrators consistent with them; the telescope is balanced (g = 0).",
           "- Fit NRMSE as in the System Identification Toolbox (100 = perfect, 0 = the mean of the measurement).", ""]
    (res_dir / "summary.md").write_text("\n".join(md))
    (res_dir / "summary.json").write_text(json.dumps(js, indent=2, default=float))
    print(f"results in {res_dir} ({time.time() - t_start:.0f} s)")


if __name__ == "__main__":
    main()
